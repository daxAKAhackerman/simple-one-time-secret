<template>
  <b-field label="Secret:" type="is-primary">
    <b-input type="textarea" v-model="secret" rows="20" max-rows="20"></b-input>
  </b-field>
  <div class="columns">
    <div class="column">
      <b-field
        type="is-primary"
        label="Expiration (local time):"
        message="Must be at most one month away"
      >
        <b-datetimepicker v-model="expiration" :max-datetime="maxExpiration"></b-datetimepicker>
      </b-field>
    </div>
    <div class="column">
      <b-field label="&nbsp;">
        <b-button expanded @click="postSecret" type="is-primary">Create secret link</b-button>
      </b-field>
    </div>
  </div>

  <h2 class="title is-2">How it works</h2>
  <p>
    Simple One Time Secret is an application that allows to securely share information using a
    single-use link. Once the secret has been viewed (or once the expiration is reached), the secret
    is deleted from the database and no longer accessible. In addition, the server only has access
    to the encrypted secret and its ID. Everything else is generated client side and is never sent
    to the server. More precisely:
  </p>
  <br />
  <div class="content">
    <ol>
      <li>
        Using JavaScript, a random encryption passphrase is generated and used to encrypt the
        secret.
      </li>
      <li>The encrypted secret is sent to the server, along with the expiration timestamp.</li>
      <li>The server replies with the ID of the secret.</li>
      <li>
        A link is generated by adding the deflated concatenation of the ID, IV and encryption key to
        the hash data of the URL. Hash data is not sent to the server when a URL is accessed.
      </li>
      <li>
        When the secret is retrieved, the server receives the ID of the secret, deletes it from the
        database, and returns the encrypted value back to the client (if it's not expired).
      </li>
      <li>
        The secret value can then be decrypted client side using the information stored in the hash
        data.
      </li>
    </ol>
  </div>
  <p>
    Want more information? Good news,
    <a href="https://github.com/daxAKAhackerman/simple-one-time-secret" target="_blank"
      >this project is open source!
    </a>
  </p>
</template>

<script setup lang="ts">
import axios from 'axios'
import { deflate } from 'pako'
import { store } from '../store.js'
import { makeToast } from '../helpers.js'
import { useToast } from 'buefy'

import { ref, computed } from 'vue'

const secret = ref('')
const initExpiration = new Date()
initExpiration.setDate(initExpiration.getDate() + 7)
const expiration = ref(initExpiration)
const toast = useToast()

const maxExpiration = computed(() => {
  const maxExp = new Date()
  maxExp.setMonth(maxExp.getMonth() + 1)
  return maxExp
})

function initNewSecret() {
  const initExpiration = new Date()
  initExpiration.setDate(initExpiration.getDate() + 7)
  expiration.value = initExpiration
  secret.value = ''
}
async function postSecret(event: Event) {
  event.preventDefault()
  const path = '/api/secret'

  const key = new Uint8Array(32)
  const iv = new Uint8Array(12)
  self.crypto.getRandomValues(key)
  self.crypto.getRandomValues(iv)

  const encryptedSecret = await encryptSecret(secret.value, key, iv)

  const payload = {
    expiration: Math.floor(expiration.value.getTime() / 1000),
    secret: btoa(String.fromCharCode(...new Uint8Array(encryptedSecret))),
  }

  axios
    .post(path, payload)
    .then((response) => {
      generateLink(response.data.id, key, iv)
      initNewSecret()
    })
    .catch((error) => {
      void error

      makeToast(toast, 'Something went wrong while creating your secret', 'is-danger')
    })
}
async function encryptSecret(data: string, key: Uint8Array, iv: Uint8Array) {
  const importedKey = await self.crypto.subtle.importKey(
    'raw',
    key.slice().buffer,
    { name: 'AES-GCM' },
    false,
    ['encrypt'],
  )
  const encodedData = Uint8Array.from(data, (c) => c.charCodeAt(0))

  const encrypted = await self.crypto.subtle.encrypt(
    { name: 'AES-GCM', iv: iv.slice().buffer },
    importedKey,
    encodedData,
  )

  return encrypted
}
function generateLink(uuid: string, key: Uint8Array, iv: Uint8Array) {
  const data = encodeURIComponent(
    btoa(
      String.fromCharCode(
        ...new Uint8Array(
          deflate(
            `${uuid};${btoa(String.fromCharCode(...iv))};${btoa(String.fromCharCode(...key))}`,
          ),
        ),
      ),
    ),
  )

  const link = `${window.location.origin}/#${data}`

  store.setLink(link)
}

initNewSecret()
</script>
